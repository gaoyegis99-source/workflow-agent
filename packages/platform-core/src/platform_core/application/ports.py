"""Ports used by P2 use cases; implemented by PostgreSQL and the test peer."""

from __future__ import annotations

from datetime import datetime
from typing import Any, Protocol

from platform_core.domain.control import Budget, ExternalObservation, Identity, Task

Record = dict[str, Any]


class AccessRepository(Protocol):
    def authorize(self, actor: Identity, project_id: str | None, role: str = "VIEWER") -> None: ...
    def role(self, actor: Identity, project_id: str) -> str: ...
    def projects(self, actor: Identity, after: str, limit: int) -> list[Record]: ...
    def project(self, project_id: str) -> Record: ...
    def create_project(self, project_id: str, name: str, actor: Identity) -> Record: ...


class TaskRepository(Protocol):
    def get(self, project_id: str, task_id: str, *, lock: bool = False) -> Task: ...
    def save(self, task: Task, *, new: bool = False) -> None: ...
    def add_spec(self, task_id: str, revision: int, spec: Record, actor_id: str) -> None: ...
    def spec(self, task_id: str, revision: int) -> Record: ...
    def list(self, project_id: str, after: str, limit: int) -> list[Task]: ...
    def state_counts(self, project_id: str) -> Record: ...
    def grants(self, project_id: str, after: str, limit: int) -> list[Record]: ...
    def active_grants(self, project_id: str, task_id: str, now: datetime) -> list[Record]: ...
    def grant(self, project_id: str, grant_id: str) -> Record: ...
    def add_grant(self, record: Record) -> None: ...
    def revoke_grant(self, grant_id: str, actor_id: str) -> None: ...
    def permits(
        self,
        task_id: str,
        target: Record,
        resources: list[Record],
        now: datetime,
        *,
        derived: bool = False,
    ) -> bool: ...


class BudgetRepository(Protocol):
    def get(self, task_id: str) -> Budget: ...
    def save(self, budget: Budget, *, new: bool = False) -> None: ...
    def reserve(self, action_id: str, task_id: str) -> None: ...
    def reservation(self, action_id: str) -> Record: ...
    def update_reservation(
        self, action_id: str, *, source: str, event_id: str, charged: bool, stopped: bool
    ) -> None: ...


class ActionRepository(Protocol):
    def get(self, action_id: str) -> Record: ...
    def add(self, record: Record) -> None: ...
    def update(self, action_id: str, **changes: Any) -> None: ...
    def active(self, task_id: str) -> list[Record]: ...
    def by_execution(self, project: str, execution: str) -> Record: ...
    def list(self, task_id: str) -> list[Record]: ...
    def project_page(
        self,
        project_id: str,
        after: str,
        limit: int,
        *,
        task_id: str | None = None,
        state: str | None = None,
    ) -> list[Record]: ...
    def state_counts(self, project_id: str) -> Record: ...
    def command(self, project_id: str, command_id: str) -> Record: ...
    def add_command(self, record: Record) -> None: ...
    def update_command(self, command_id: str, **changes: Any) -> None: ...


class DeliveryRepository(Protocol):
    def replay(self, actor: Identity, scope: str, operation: str, key: str) -> Record | None: ...
    def idempotency(
        self, actor: Identity, scope: str, operation: str, key: str, digest: str
    ) -> Record | None: ...
    def remember(
        self, actor: Identity, scope: str, operation: str, key: str, result: Record
    ) -> None: ...
    def enqueue(self, event_id: str, task_id: str, kind: str, payload: Record) -> None: ...
    def claim(self, owner: str, lease_seconds: float) -> Record | None: ...
    def owned(self, event_id: str, owner: str, generation: int) -> bool: ...
    def renew(self, event_id: str, owner: str, generation: int, seconds: float) -> bool: ...
    def finish(
        self, event_id: str, owner: str, generation: int, delay: float | None = None
    ) -> None: ...
    def inbox(self, source: str, event_id: str, digest: str) -> bool: ...
    def audit(self, event_id: str, task_id: str, payload: Record) -> None: ...


class ScienceRepository(Protocol):
    def permit(self, action_id: str, execution_id: str, attempt_id: str) -> None: ...
    def candidates(self, task_id: str) -> list[Record]: ...
    def candidate(self, project: str, id: str) -> Record: ...
    def add_candidate(self, record: Record) -> None: ...
    def checks(self, task_id: str) -> list[Record]: ...
    def check(self, project: str, id: str) -> Record: ...
    def add_check(self, record: Record) -> None: ...
    def pending_checks(self) -> list[Record]: ...
    def report(self, id: str, status: str, report: Record, digest: str) -> None: ...
    def complete(self, task: Task, acceptance: Record) -> None: ...
    def completion(self, task_id: str) -> Record | None: ...
    def add_plan(self, plan: Record, items: list[Record], evidence: list[Record]) -> None: ...
    def plan(self, acceptance_id: str) -> Record | None: ...
    def apply_item_results(self, plan_id: str, results: list[Record]) -> None: ...
    def update_check(
        self, acceptance_id: str, status: str, report: Record, digest: str
    ) -> None: ...
    def mark_plan_stale(self, acceptance_id: str) -> None: ...
    def add_review(self, record: Record) -> None: ...
    def reviews(self, acceptance_id: str) -> list[Record]: ...
    def set_completion_validity(
        self, task_id: str, validity: str, reason: Record | None = None
    ) -> None: ...
    def validity(self, task_id: str) -> Record | None: ...
    def apply_knowledge_event(self, event: Record) -> list[Record]: ...


class WorkflowRepository(Protocol):
    def add_package(self, record: Record) -> None: ...
    def package(self, project_id: str, package_id: str) -> Record: ...
    def packages(self, project_id: str, after: str, limit: int) -> list[Record]: ...
    def claim_package(self, owner: str, lease_seconds: float) -> Record | None: ...
    def finish_package(
        self,
        package_id: str,
        owner: str,
        generation: int,
        *,
        status: str,
        compiled: Record | None,
        error: Record | None,
    ) -> bool: ...
    def add_envelope(self, action_id: str, amount: int) -> None: ...
    def envelope(self, action_id: str, *, required: bool = True) -> Record | None: ...
    def release_envelope(self, action_id: str) -> int: ...
    def node(self, node_id: str, *, lock: bool = False) -> Record | None: ...
    def add_node(self, record: Record) -> None: ...
    def nodes(self, action_id: str, after: str = "", limit: int = 1001) -> list[Record]: ...
    def update_node(self, node_id: str, **changes: Any) -> None: ...


class AuthoringRepository(Protocol):
    def workspace_counts(self, project_id: str) -> Record: ...
    def add_definition(self, definition: Record, revision: Record) -> None: ...
    def definition(self, project_id: str, definition_id: str, *, lock: bool = False) -> Record: ...
    def definitions(self, project_id: str, after: str, limit: int) -> list[Record]: ...
    def add_revision(self, project_id: str, definition_id: str, revision: Record) -> None: ...
    def revision(self, project_id: str, definition_id: str, revision: int) -> Record: ...
    def revisions(
        self, project_id: str, definition_id: str, after: int, limit: int
    ) -> list[Record]: ...
    def add_validation(self, record: Record) -> None: ...
    def validation(self, project_id: str, validation_id: str) -> Record: ...
    def claim_validation(self, owner: str, lease_seconds: float) -> Record | None: ...
    def finish_validation(
        self,
        validation_id: str,
        owner: str,
        generation: int,
        *,
        status: str,
        issues: list[Record],
    ) -> bool: ...
    def add_candidate(self, record: Record) -> None: ...
    def candidate(self, project_id: str, definition_id: str, candidate_id: str) -> Record: ...
    def candidate_by_package(self, package_id: str) -> Record | None: ...
    def candidates(
        self, project_id: str, definition_id: str, after: str, limit: int
    ) -> list[Record]: ...
    def add_trial(self, record: Record) -> None: ...
    def trial(self, project_id: str, definition_id: str, trial_id: str) -> Record: ...
    def trials(
        self, project_id: str, definition_id: str, after: str, limit: int
    ) -> list[Record]: ...
    def claim_trial(self, owner: str, lease_seconds: float) -> Record | None: ...
    def finish_trial(
        self,
        trial_id: str,
        owner: str,
        generation: int,
        **changes: Any,
    ) -> bool: ...
    def add_release(self, record: Record, trials: list[Record]) -> None: ...
    def release(
        self, project_id: str, definition_id: str, version_label: str, *, lock: bool = False
    ) -> Record: ...
    def releases(
        self, project_id: str, definition_id: str, after: str, limit: int
    ) -> list[Record]: ...
    def release_by_id(self, project_id: str, release_id: str, *, lock: bool = False) -> Record: ...
    def project_releases(self, project_id: str, after: str, limit: int) -> list[Record]: ...
    def release_trials(self, release_id: str) -> list[Record]: ...
    def release_lifecycle_events(self, release_id: str, after: int, limit: int) -> list[Record]: ...
    def transition_release(self, release_id: str, event: Record) -> None: ...
    def release_publication_permit(self, action_id: str) -> Record | None: ...
    def add_release_publication_permit(self, record: Record) -> None: ...


class UnitOfWork(Protocol):
    access: AccessRepository
    tasks: TaskRepository
    budgets: BudgetRepository
    actions: ActionRepository
    delivery: DeliveryRepository
    science: ScienceRepository
    research: Any
    workflows: WorkflowRepository
    authoring: AuthoringRepository
    service_bindings: Any
    agents: Any

    def __enter__(self) -> UnitOfWork: ...
    def __exit__(self, *args: Any) -> None: ...
    def now(self) -> datetime: ...
    def new_id(self) -> str: ...


class Store(Protocol):
    def transaction(self) -> UnitOfWork: ...


class ExecutionPort(Protocol):
    def submit(self, action_id: str, request: Record) -> ExternalObservation: ...
    def query(self, action_id: str) -> ExternalObservation | None: ...
    def cancel(self, action_id: str) -> ExternalObservation: ...
