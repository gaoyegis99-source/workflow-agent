class UnitOfWork(Protocol):
    access: AccessRepository
    tasks: TaskRepository
    budgets: BudgetRepository
    actions: ActionRepository
    delivery: DeliveryRepository
    science: ScienceRepository
    research: ResearchRepository
    workflows: WorkflowRepository
    authoring: AuthoringRepository
    service_bindings: ServiceBindingRepository
    agent_runs: AgentRunLeaseRepository
    agent_conversations: AgentConversationRepository
    agent_tools: AgentToolRepository
    agent_budgets: AgentBudgetRepository
    agent_recovery: AgentRecoveryRepository

    def __enter__(self) -> UnitOfWork: ...
    def __exit__(self, *args: Any) -> None: ...
    def now(self) -> datetime: ...
    def new_id(self) -> str: ...


class Store(Protocol):
    def transaction(self) -> UnitOfWork: ...


